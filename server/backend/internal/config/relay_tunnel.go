package config

// GRE tunnel between a reserve entry and the Hub (incident 2026-11-20): a transit link between
// the providers lost every packet of some 5-tuples towards one entry (the same source port always
// failed, another always passed; 40–60 % of the flows), while ping and raw GRE/IPIP passed 10/10 —
// they carry no ports, so ECMP hashes them on the two addresses only. Inside one GRE tunnel every
// flow of the entry rides the same outer pair of addresses: the path works for all of them or for
// none (and then the entries monitor takes the entry out of the subscriptions).
//
//	relay he-hub  <relay tunnel address>  ── GRE (proto 47) relay public ↔ Hub public ──
//	Hub   he-r<id> <hub tunnel address>
//
// Everything the relay sends to the Hub goes through it: the DNAT of TCP 2443 and UDP
// 30000-65000 (relay_nft.go) and the nginx stream of 443/80 (relay_stream.go, with the Hub's
// public address as the backup upstream). The addresses come from RelayTunnelPool, one /30 per
// relay id, point-to-point (`ip addr add <own> peer <other>`): the Hub's address is base+4·id+1,
// the relay's base+4·id+2. The pool is checked against the routes and addresses of both ends
// before anything is created (TunnelOverlap).
//
// Each end is a oneshot unit (TunnelUnit) that creates the device at boot and deletes it on stop;
// no netplan or ifupdown file: the network configuration of the Hub and of the relay is never
// regenerated for a tunnel.

import (
	"errors"
	"fmt"
	"net/netip"
	"regexp"
	"strconv"
	"strings"
)

const (
	RelayTunnelPool = "10.77.0.0/16"
	// RelayTunnelMTU: 1500 − the outer IPv4 header (20) − the GRE header without key (4).
	RelayTunnelMTU = 1476
	// RelayTunnelDev / RelayTunnelUnitName: the relay's end (one tunnel per relay).
	RelayTunnelDev      = "he-hub"
	RelayTunnelUnitName = "heyearth-tunnel.service"
	// RelayTunnelMaxID: the last relay id the pool has a /30 for.
	RelayTunnelMaxID = 16383
)

var (
	relayTunnelPool = netip.MustParsePrefix(RelayTunnelPool)
	tunnelDevRe     = regexp.MustCompile(`^he-[a-z0-9]{1,12}$`) // IFNAMSIZ: at most 15 characters
)

// RelayTunnelAddrs: the Hub's and the relay's tunnel address of relay id.
func RelayTunnelAddrs(id int) (hub, relay netip.Addr, err error) {
	if id < 1 || id > RelayTunnelMaxID {
		return netip.Addr{}, netip.Addr{}, fmt.Errorf("id входа %d вне 1..%d — для туннеля нет адресов", id, RelayTunnelMaxID)
	}
	b := relayTunnelPool.Addr().As4()
	off := 4*id + 1
	b[2], b[3] = byte(off>>8), byte(off)
	hub = netip.AddrFrom4(b)
	return hub, hub.Next(), nil
}

// RelayTunnelBlock: the /30 of relay id (what TunnelOverlap keeps free).
func RelayTunnelBlock(id int) (netip.Prefix, error) {
	hub, _, err := RelayTunnelAddrs(id)
	if err != nil {
		return netip.Prefix{}, err
	}
	return netip.PrefixFrom(hub, 30).Masked(), nil
}

// InRelayTunnelPool: a tunnel address of some relay (the Hub trusts it like the relay's own).
func InRelayTunnelPool(a netip.Addr) bool { return relayTunnelPool.Contains(a.Unmap()) }

// HubTunnelDev / HubTunnelUnitName: the Hub's end of relay id's tunnel.
func HubTunnelDev(id int) string      { return "he-r" + strconv.Itoa(id) }
func HubTunnelUnitName(id int) string { return "heyearth-tunnel-r" + strconv.Itoa(id) + ".service" }

// HubTunnelUFWComment marks the Hub's ufw rule that lets relay id's GRE in.
func HubTunnelUFWComment(id int) string { return "heyearth-tunnel-" + strconv.Itoa(id) }

// TunnelUnit is the unit of one end: dev from local to remote (public IPv4, RelayHubIP rules),
// own address addr with the other end peer (both in RelayTunnelPool). A start deletes a leftover
// device first, so a restart re-creates it with the file's values (a changed Hub address).
// A start that fails (at boot, say) is retried every 5 s: the relay's DNAT points into the
// tunnel and has no other way to the Hub.
func TunnelUnit(dev, local, remote string, addr, peer netip.Addr) (string, error) {
	if !tunnelDevRe.MatchString(dev) {
		return "", fmt.Errorf("имя интерфейса туннеля %q не подходит", dev)
	}
	l, err := RelayHubIP(local)
	if err != nil {
		return "", fmt.Errorf("свой адрес туннеля: %w", err)
	}
	r, err := RelayHubIP(remote)
	if err != nil {
		return "", fmt.Errorf("адрес другого конца туннеля: %w", err)
	}
	if l == r {
		return "", errors.New("у туннеля оба конца — один адрес")
	}
	if !InRelayTunnelPool(addr) || !InRelayTunnelPool(peer) || addr == peer {
		return "", fmt.Errorf("адреса туннеля %s и %s должны быть разными и из %s", addr, peer, RelayTunnelPool)
	}
	return fmt.Sprintf(`# Generated by heyearth (config.TunnelUnit): GRE %[2]s <-> %[3]s, %[4]s -> %[5]s. Do not edit.
[Unit]
Description=HiEarth GRE tunnel %[1]s to %[3]s
After=network-online.target
Wants=network-online.target
[Service]
Type=oneshot
RemainAfterExit=yes
Restart=on-failure
RestartSec=5
ExecStartPre=-ip link del %[1]s
ExecStart=ip tunnel add %[1]s mode gre local %[2]s remote %[3]s ttl 64
ExecStart=ip addr add %[4]s peer %[5]s dev %[1]s
ExecStart=ip link set %[1]s mtu %[6]d up
ExecStop=-ip link del %[1]s
[Install]
WantedBy=multi-user.target
`, dev, l, r, addr.Unmap(), peer.Unmap(), RelayTunnelMTU), nil
}

// routeTypes are the type words `ip route show table all` may print before the prefix.
var routeTypes = map[string]bool{"unicast": true, "local": true, "broadcast": true, "multicast": true, "blackhole": true,
	"unreachable": true, "prohibit": true, "throw": true, "nat": true, "anycast": true}

// TunnelOverlap refuses a tunnel whose block would collide with this host's network: any route
// (of any table) or address that overlaps block and does not belong to the tunnel's own device dev
// (a re-run sees its own routes). routes is `ip -4 -o route show table all`, addrs is
// `ip -4 -o addr show`. Default routes cover everything and are skipped. A line that cannot be
// read is an error: an unknown format must not pass as "free".
func TunnelOverlap(routes, addrs, dev string, block netip.Prefix) error {
	own := func(f []string) bool {
		for i := 0; i+1 < len(f); i++ {
			if f[i] == "dev" && strings.TrimSuffix(f[i+1], "\\") == dev {
				return true
			}
		}
		return false
	}
	for _, line := range strings.Split(routes, "\n") {
		f := strings.Fields(line)
		if len(f) > 0 && routeTypes[f[0]] {
			f = f[1:]
		}
		if len(f) == 0 || f[0] == "default" || own(f) {
			continue
		}
		p, err := parsePrefixOrAddr(f[0])
		if err != nil {
			return fmt.Errorf("маршрут %q не разобран: %w", strings.TrimSpace(line), err)
		}
		if p.Bits() > 0 && p.Overlaps(block) {
			return fmt.Errorf("маршрут %q пересекается с адресами туннеля %s", strings.TrimSpace(line), block)
		}
	}
	for _, line := range strings.Split(addrs, "\n") {
		f := strings.Fields(line)
		if len(f) < 4 {
			continue
		}
		name := strings.TrimSuffix(strings.Split(f[1], "@")[0], ":")
		if name == dev {
			continue
		}
		for i := 2; i+1 < len(f); i++ {
			if f[i] != "inet" && f[i] != "peer" {
				continue
			}
			p, err := parsePrefixOrAddr(f[i+1])
			if err != nil {
				return fmt.Errorf("адрес %q не разобран: %w", strings.TrimSpace(line), err)
			}
			if p.Overlaps(block) {
				return fmt.Errorf("адрес %s на %s пересекается с адресами туннеля %s", f[i+1], name, block)
			}
		}
	}
	return nil
}

func parsePrefixOrAddr(s string) (netip.Prefix, error) {
	if strings.Contains(s, "/") {
		return netip.ParsePrefix(s)
	}
	a, err := netip.ParseAddr(s)
	if err != nil {
		return netip.Prefix{}, err
	}
	return netip.PrefixFrom(a, a.BitLen()), nil
}

// relayTunnelTarget validates the Hub's tunnel address a relay forwards to: one of the pool.
func relayTunnelTarget(s string) (netip.Addr, error) {
	a, err := netip.ParseAddr(strings.TrimSpace(s))
	if err != nil || !a.Is4() || !InRelayTunnelPool(a) {
		return netip.Addr{}, fmt.Errorf("адрес туннеля Hub %q: нужен адрес из %s", s, RelayTunnelPool)
	}
	return a, nil
}
