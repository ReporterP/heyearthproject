// ExitHysteriaServerYAML renders the exit's hysteria server (the Hub→exit tunnel): production
// tuning (QUIC windows 26843545/67108864, Brutal 100/100 mbps, the 2026-10-12 benchmark; the same
// as the Hub's clients, HubHysteriaClientYAML) and the shared ACL (ExitHysteriaACL, MTProxy port
// allowed on the exit's own address; mtprotoPort 0 = no allowance). Contract: the caller checks
// exitIP with ValidateExitIP first — this renderer cannot fail and, like ExitHysteriaACL, leaves
// out the own-address rules for a non-IP. The password goes through yamlPassword (as the Hub's
// client, HubHysteriaClientYAML): padded base64 unquoted as on the running exits, anything else
// double-quoted, so it can never add keys or ACL rules.
func ExitHysteriaServerYAML(password, exitIP string, ownTCPPorts ...int) string {
	return `# Generated by heyearth (config.ExitHysteriaServerYAML)
listen: :` + strconv.Itoa(ExitHysteriaPort) + `

tls:
  cert: ` + ExitHysteriaCert + `
  key: ` + ExitHysteriaKey + `

auth:
  type: password
  password: ` + yamlPassword(password) + `

masquerade:
  type: proxy
  proxy:
    url: https://www.microsoft.com
    rewriteHost: true

quic:
  initStreamReceiveWindow: 26843545
  maxStreamReceiveWindow: 26843545
  initConnReceiveWindow: 67108864
  maxConnReceiveWindow: 67108864

bandwidth:
  up: 100 mbps
  down: 100 mbps

` + ExitHysteriaACL(exitIP, ownTCPPorts...)
}

// yamlPassword renders a hysteria password for both ends of the tunnel (ExitHysteriaServerYAML,
// HubHysteriaClientYAML), so they always parse the same string: a padded base64 value stays a
// plain scalar (it can neither start an indicator nor resolve to a number, bool or null);
// anything else is double-quoted (Go escapes are valid YAML double-quoted escapes).
func yamlPassword(s string) string {
	plain := len(s) > 1 && s[0] != '=' && s[len(s)-1] == '='
	for i := 0; plain && i < len(s); i++ {
		c := s[i]
		plain = c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '+' || c == '/' || c == '='
	}
	if plain {
		return s
	}
	return strconv.Quote(s)
}

