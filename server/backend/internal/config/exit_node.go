// ExitXrayConfigJSON renders /opt/heyearth/xray/config.json of an exit: only the Hub's TCP
// fallback tunnel — VLESS Reality inbound "vless-reality" on 0.0.0.0:10443, flow
// xtls-rprx-vision, dest microsoft.com:443, the Hub's UUID as the one client — with the guard
// rules shared with the hysteria ACL (ExitXrayGuardRules; mtprotoPort 0 = no allowance) and
// BitTorrent blocked. The Shadowsocks inbounds older exits still run (shadowsocks-ws :443,
// shadowsocks-tcp :8388) are deliberately absent: since phase 1 nothing on the Hub dials them,
// so converging such an exit reports its config as drift and rewrites it without them.
// exitIP must pass ValidateExitIP: without it the guard could not block the exit's own address.
// The routing guard sees only what the router sees (not XUDP per-packet targets): the kernel
// guard ExitXrayGuardConf is the second layer.
func ExitXrayConfigJSON(k ExitRealityKeys, exitIP string, mtprotoPort int) ([]byte, error) {
	if err := ValidateExitIP(exitIP); err != nil {
		return nil, err
	}
	ip := canonicalIP(exitIP)
	var rules []any
	if err := json.Unmarshal([]byte("["+ExitXrayGuardRules(ip, "direct", "block", mtprotoPort)+"]"), &rules); err != nil {
		return nil, fmt.Errorf("guard rules: %w", err)
	}
	rules = append(rules, map[string]any{"type": "field", "protocol": []string{"bittorrent"}, "outboundTag": "block"})
	sockopt := map[string]any{"tcpFastOpen": true, "tcpNoDelay": true, "tcpKeepAliveInterval": 30}
	cfg := map[string]any{
		"log": map[string]any{"loglevel": "warning"},
		"dns": map[string]any{"servers": []string{"8.8.8.8", "1.1.1.1"}, "queryStrategy": "UseIPv4"},
		"inbounds": []any{map[string]any{
			"tag": "vless-reality", "listen": "0.0.0.0", "port": ExitRealityPort, "protocol": "vless",
			"settings": map[string]any{"decryption": "none",
				"clients": []any{map[string]any{"id": k.UUID, "flow": ExitRealityFlow}}},
			"streamSettings": map[string]any{"network": "tcp", "security": "reality", "sockopt": sockopt,
				"realitySettings": map[string]any{"show": false, "dest": ExitRealityDest, "xver": 0,
					"serverNames": ExitRealityServerNames(),
					"privateKey":  k.PrivateKey, "shortIds": []string{k.ShortID}}},
			"sniffing": map[string]any{"enabled": true, "destOverride": []string{"http", "tls", "quic"}},
		}},
		"outbounds": []any{
			map[string]any{"protocol": "freedom", "tag": "direct", "settings": map[string]any{"domainStrategy": "UseIPv4"},
				"streamSettings": map[string]any{"sockopt": sockopt}},
			map[string]any{"protocol": "blackhole", "tag": "block", "settings": map[string]any{"response": map[string]any{"type": "none"}}},
		},
		"routing": map[string]any{"domainStrategy": "IPIfNonMatch", "rules": rules},
		"policy": map[string]any{"levels": map[string]any{"0": map[string]any{
			"handshake": 4, "connIdle": 300, "uplinkOnly": 2, "downlinkOnly": 5, "bufferSize": 512}}},
	}
	b, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// RealityProbe is what the Hub needs to dial an exit's TCP fallback. SNI "" = ExitRealitySNI.
type RealityProbe struct{ ExitIP, UUID, PublicKey, ShortID, SNI string }

// VRProbeSocksPort is the loopback SOCKS of the short-lived Hub xray that checks exit <id>'s TCP
// path (3088..3599: outside the hysteria clients' 1088..1599, the main xray's probe inbounds
// 12000+id and every Hub listener).
func VRProbeSocksPort(serverID int) int { return 3088 + serverID }

// ExitRealityProbeConfig renders a minimal xray client: SOCKS on 127.0.0.1:socksPort → VLESS
// Reality to <exit>:10443 with what the Hub's exit-<id>.vr outbound dials (cmd/api
// exitVROutbound): flow ExitRealityFlow, fingerprint ExitVRFingerprint, the SNI (default
// ExitRealitySNI), the exit's public key and short id (left out when empty), no mux.
func ExitRealityProbeConfig(socksPort int, p RealityProbe) ([]byte, error) {
	if err := ValidateExitIP(p.ExitIP); err != nil {
		return nil, err
	}
	ip := canonicalIP(p.ExitIP)
	switch {
	case p.UUID == "" || p.PublicKey == "":
		return nil, fmt.Errorf("exit %s: tunnel UUID or Reality public key missing", ip)
	case socksPort < 1 || socksPort > 65535:
		return nil, fmt.Errorf("probe SOCKS port %d outside 1..65535", socksPort)
	}
	sni := p.SNI
	if sni == "" {
		sni = ExitRealitySNI
	}
	reality := map[string]any{"fingerprint": ExitVRFingerprint, "serverName": sni, "publicKey": p.PublicKey}
	if p.ShortID != "" {
		reality["shortId"] = p.ShortID
	}
	cfg := map[string]any{
		"log": map[string]any{"loglevel": "warning"},
		"inbounds": []any{map[string]any{"listen": "127.0.0.1", "port": socksPort, "protocol": "socks",
			"settings": map[string]any{"auth": "noauth", "udp": false}}},
		"outbounds": []any{map[string]any{"protocol": "vless",
			"settings": map[string]any{"vnext": []any{map[string]any{"address": ip, "port": ExitRealityPort,
				"users": []any{map[string]any{"id": p.UUID, "encryption": "none", "flow": ExitRealityFlow}}}}},
			"streamSettings": map[string]any{"network": "tcp", "security": "reality", "realitySettings": reality}}},
	}
	b, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}
