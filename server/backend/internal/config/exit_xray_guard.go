// Kernel egress guard of an exit's xray.
//
// Why a kernel layer. The exit xray's routing guard (ExitXrayGuardRules) only judges what the
// router sees: XUDP (mux) packets carry a destination per packet and freedom sends them without
// another routing pass, and between IPIfNonMatch and freedom's UseIPv4 a name can resolve
// differently (DNS rebinding). So UDP — or a TCP target behind a domain — through exit-<id>.vr
// could reach the exit's loopback services, its private neighbours or its own address. As on
// the Hub (cmd/deploy/ops_egress_guard.go), the last word belongs to the kernel, keyed on WHO
// sends: xray runs as the system user ExitXrayUser (ExitXrayUnit), and an nftables output chain
// rejects that user's packets to:
//
//	the exit's own address, except tcp/<MTProxy port> (mirrors ExitHysteriaACL)
//	exitBlockedRanges: 127/8, ::1, 0/8, ::, RFC1918, 100.64/10, 169.254/16, fc00::/7, fe80::/10
//	multicast and broadcast: 224.0.0.0/4, 255.255.255.255, ff00::/8
//	any local, multicast or broadcast address of the host (fib daddr type, evaluated per
//	  packet: docker0, subnet broadcasts and addresses added later included)
//
// No exception, DNS included. xray resolves through its own dns block (8.8.8.8, 1.1.1.1 —
// ExitXrayConfigJSON), and the one thing that uses the system resolver — REALITY dialling its
// dest (microsoft.com:443) with Go's resolver on every handshake — reads ExitXrayResolvConf
// (the same public servers), which ExitXrayUnit bind-mounts over /etc/resolv.conf for xray only:
// the host's 127.0.0.53 or provider resolver is never needed, so none of them is reachable
// through the tunnel. The rules apply to every packet of the user, replies included: nothing on
// the exit talks to xray over loopback or its own address (the Hub dials the public :10443).
//
// The ruleset lives in its own table, ExitXrayGuardTable, in ExitXrayGuardConfPath: the file
// creates, deletes and defines the table in one nft transaction (idempotent, no window without
// rules), and the oneshot unit ExitXrayGuardUnit loads it at boot. xray.service Requires= that
// unit, so xray never runs without the guard; re-applying uses `nft -f` (a restart of the guard
// unit restarts xray too). The guard unit is PartOf= nftables.service and ordered after it: a
// `systemctl restart nftables` (its config starts with `flush ruleset`) re-applies the guard
// and restarts xray; a `systemctl reload nftables` (the same flush) re-applies it through
// ReloadPropagatedFrom= + ExecReload= without touching xray; stopping nftables stops xray. Rules
// name the user, not a uid: the user must exist before the file is loaded (ExitXrayUserScript).

const (
	ExitXrayUser          = "xray"
	ExitXrayGuardTable    = "heyearth_exit_guard"
	ExitXrayGuardConfPath = "/etc/nftables-heyearth-exit-guard.conf"
	ExitXrayGuardService  = "heyearth-exit-guard"
	ExitXrayGuardUnitPath = "/etc/systemd/system/" + ExitXrayGuardService + ".service"

	// ExitXrayResolvConfPath is the resolv.conf xray sees (ExitXrayUnit BindReadOnlyPaths).
	ExitXrayResolvConfPath = "/opt/heyearth/xray/resolv.conf"
	// ExitXrayResolvConf: the same public servers as xray's dns block (exitXrayDNSServers), short
	// timeouts so a lost datagram does not stall a REALITY handshake for Go's default 5 s.
	ExitXrayResolvConf = `# Generated by heyearth (config.ExitXrayResolvConf): xray's /etc/resolv.conf (bind-mounted).
nameserver 8.8.8.8
nameserver 1.1.1.1
options timeout:2 attempts:2
`
)

// exitXrayDNSServers is the dns block of the exit xray (ExitXrayConfigJSON); ExitXrayResolvConf
// names the same servers.
var exitXrayDNSServers = []string{"8.8.8.8", "1.1.1.1"}

// ValidateExitIP is the caller contract of every exit renderer (ExitHysteriaServerYAML,
// ExitHysteriaACL, ExitXrayConfigJSON, ExitXrayGuardConf, ExitRealityProbeConfig): the exit
// address must be a unicast IP literal. ExitHysteriaServerYAML / ExitHysteriaACL cannot fail and
// silently leave out the own-address rules for anything else, so the provisioning core
// (internal/provision ExitRecipe, Task 2.8) and the CLI call this before rendering; the renderers
// that return an error call it themselves.
func ValidateExitIP(exitIP string) error {
	ip := net.ParseIP(strings.TrimSpace(exitIP))
	switch {
	case ip == nil:
		return fmt.Errorf("exit address %q is not an IP address", exitIP)
	case ip.IsUnspecified() || ip.IsLoopback() || ip.IsMulticast() || ip.IsLinkLocalUnicast() || ip.IsLinkLocalMulticast():
		return fmt.Errorf("exit address %s is not a unicast host address", ip)
	}
	return nil
}

// ExitXrayGuardConf renders ExitXrayGuardConfPath for the exit exitIP (ValidateExitIP) with the
// MTProxy port allowed on its own address (0 = none), the same allowance as ExitHysteriaACL.
func ExitXrayGuardConf(exitIP string, mtprotoPort int) (string, error) {
	if err := ValidateExitIP(exitIP); err != nil {
		return "", err
	}
	ip := canonicalIP(exitIP)
	fam := "ip"
	if strings.Contains(ip, ":") {
		fam = "ip6"
	}
	var v4, v6 []string
	for _, n := range exitBlockedRanges {
		if strings.Contains(n, ":") {
			v6 = append(v6, n)
		} else {
			v4 = append(v4, n)
		}
	}
	v4 = append(v4, "224.0.0.0/4", "255.255.255.255/32")
	v6 = append(v6, "ff00::/8")
	set := func(s []string) string { return "{ " + strings.Join(s, ", ") + " }" }

	var b strings.Builder
	b.WriteString("# Generated by heyearth (config.ExitXrayGuardConf): what the exit's xray (user " + ExitXrayUser + ") may not reach.\n")
	b.WriteString("table inet " + ExitXrayGuardTable + "\ndelete table inet " + ExitXrayGuardTable + "\ntable inet " + ExitXrayGuardTable + " {\n")
	b.WriteString("  chain output {\n    type filter hook output priority filter; policy accept;\n")
	b.WriteString("    meta skuid \"" + ExitXrayUser + "\" jump xray_egress\n  }\n")
	b.WriteString("  chain xray_egress {\n")
	for _, p := range validPorts([]int{mtprotoPort}) {
		b.WriteString("    " + fam + " daddr " + ip + " tcp dport " + strconv.Itoa(p) + " return\n")
	}
	if fam == "ip" {
		v4 = append(v4, ip)
	} else {
		v6 = append(v6, ip)
	}
	b.WriteString("    ip daddr " + set(v4) + " counter reject\n")
	b.WriteString("    ip6 daddr " + set(v6) + " counter reject\n")
	b.WriteString("    fib daddr type { local, multicast, broadcast } counter reject\n")
	b.WriteString("  }\n}\n")
	return b.String(), nil
}

// ExitXrayGuardUnit loads ExitXrayGuardConfPath at boot, before xray (which Requires= it), and
// again whenever nftables.service is restarted (PartOf=) or reloaded (ReloadPropagatedFrom= +
// ExecReload=: a reload's `flush ruleset` would drop the guard, and PartOf= does not propagate
// reloads). Ordered after nftables.service, so the reload lands after its flush.
const ExitXrayGuardUnit = `[Unit]
Description=Kernel egress guard of the exit xray (HeYearth)
After=network.target nftables.service
PartOf=nftables.service
ReloadPropagatedFrom=nftables.service
Before=xray.service
[Service]
Type=oneshot
ExecStart=/usr/sbin/nft -f ` + ExitXrayGuardConfPath + `
ExecReload=/usr/sbin/nft -f ` + ExitXrayGuardConfPath + `
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
`

// ExitXrayUserScript creates the system group and user xray runs as (no login, no home), once;
// a group left without its user (e.g. by an old package) is reused, not a useradd failure.
const ExitXrayUserScript = `getent group ` + ExitXrayUser + ` >/dev/null || groupadd --system ` + ExitXrayUser + `
if ! id -u ` + ExitXrayUser + ` >/dev/null 2>&1; then
  useradd --system -g ` + ExitXrayUser + ` --no-create-home --shell /usr/sbin/nologin ` + ExitXrayUser + `
  echo "[xray] system user ` + ExitXrayUser + ` created"
fi
`

// ExitXrayGuardApplyScript (re)loads the guard written to ExitXrayGuardConfPath / ExitXrayGuardUnitPath
// and enables its boot unit; under set -e a failure stops the caller.
const ExitXrayGuardApplyScript = `nft -f ` + ExitXrayGuardConfPath + `
systemctl daemon-reload
systemctl enable ` + ExitXrayGuardService + ` >/dev/null 2>&1
echo "[xray] egress guard applied (table inet ` + ExitXrayGuardTable + `, user ` + ExitXrayUser + `)"
`

// ExitXrayGuardScript is the whole guard install for a shell caller (deploy --setup-exit-node),
// built from the same parts the provisioning core uses: the user, xray's resolv.conf, the two
// guard files, the apply. Run as root under set -e, before xray.service (re)starts with
// ExitXrayUnit (which needs ExitXrayResolvConfPath to exist: BindReadOnlyPaths fails closed).
func ExitXrayGuardScript(exitIP string, mtprotoPort int) (string, error) {
	conf, err := ExitXrayGuardConf(exitIP, mtprotoPort)
	if err != nil {
		return "", err
	}
	return ExitXrayUserScript +
		"mkdir -p " + path.Dir(ExitXrayResolvConfPath) + "\n" +
		"cat > " + ExitXrayResolvConfPath + " << 'REOF'\n" + ExitXrayResolvConf + "REOF\n" +
		"cat > " + ExitXrayGuardConfPath + " << 'GEOF'\n" + conf + "GEOF\n" +
		"cat > " + ExitXrayGuardUnitPath + " << 'SEOF'\n" + ExitXrayGuardUnit + "SEOF\n" +
		ExitXrayGuardApplyScript, nil
}
