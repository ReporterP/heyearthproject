// Kernel egress guard of an exit's backup tunnel (sing-box: ShadowTLS v3 + Shadowsocks 2022,
// exit_stls.go).
//
// Why a kernel layer. The sing-box route rules (ExitSTLSServerJSON) only judge what the router
// sees, and a name can resolve differently between the rule and the dial (DNS rebinding). So a
// target behind a domain — or UDP over UoT — through the exit's backup tunnel could reach the
// exit's loopback services, its private neighbours or its own address. As on the Hub
// (cmd/deploy/ops_egress_guard.go), the last word belongs to the kernel, keyed on WHO sends:
// sing-box runs as the system user ExitSTLSUser (ExitSTLSUnitFile), and an nftables output chain
// rejects that user's packets to:
//
//	the exit's own address, except tcp/<MTProxy port> (mirrors ExitHysteriaACL)
//	exitBlockedRanges: 127/8, ::1, 0/8, ::, RFC1918, 100.64/10, 169.254/16, fc00::/7, fe80::/10
//	multicast and broadcast: 224.0.0.0/4, 255.255.255.255, ff00::/8
//	any local, multicast or broadcast address of the host (fib daddr type, evaluated per
//	  packet: docker0, subnet broadcasts and addresses added later included)
//
// The rules apply to every packet of the user, replies included — and the Shadowsocks inbound
// behind ShadowTLS listens on loopback: the ShadowTLS inbound hands connections to it inside the
// process (detour), never through a socket, so the guard does not cut that hop. DNS has no
// exception either: sing-box resolves through its own dns block (8.8.8.8, 1.1.1.1), and anything
// that would fall back to the system resolver reads ExitSTLSResolvConf (the same public
// servers), which ExitSTLSUnitFile bind-mounts over /etc/resolv.conf for sing-box only: the
// host's 127.0.0.53 or provider resolver is never needed, so none of them is reachable through
// the tunnel.
//
// The ruleset lives in its own table, ExitGuardTable, in ExitGuardConfPath: the file creates,
// deletes and defines the table in one nft transaction (idempotent, no window without rules),
// and the oneshot unit ExitGuardUnit loads it at boot. The tunnel unit Requires= that unit, so
// sing-box never runs without the guard; re-applying uses `nft -f` (a restart of the guard unit
// restarts the tunnel too). The guard unit is PartOf= nftables.service and ordered after it: a
// `systemctl restart nftables` (its config starts with `flush ruleset`) re-applies the guard and
// restarts the tunnel; a `systemctl reload nftables` (the same flush) re-applies it through
// ReloadPropagatedFrom= + ExecReload= without touching the tunnel; stopping nftables stops the
// tunnel. Rules name the user, not a uid: the user must exist before the file is loaded
// (ExitSTLSUserScript). Until 2026-11-16 the same guard (same file, table and unit) covered the
// exit's xray (VLESS Reality :10443, user xray), retired by the recipe's retire_xray step.

const (
	ExitSTLSUser      = "stls"
	ExitGuardTable    = "heyearth_exit_guard"
	ExitGuardConfPath = "/etc/nftables-heyearth-exit-guard.conf"
	ExitGuardService  = "heyearth-exit-guard"
	ExitGuardUnitPath = "/etc/systemd/system/" + ExitGuardService + ".service"

	// ExitSTLSResolvConfPath is the resolv.conf sing-box sees (ExitSTLSUnitFile BindReadOnlyPaths).
	ExitSTLSResolvConfPath = SingBoxDir + "/resolv.conf"
	// ExitSTLSResolvConf: the same public servers as sing-box's dns block (exitSTLSDNSServers),
	// short timeouts so a lost datagram does not stall a handshake for Go's default 5 s.
	ExitSTLSResolvConf = `# Generated by heyearth (config.ExitSTLSResolvConf): sing-box's /etc/resolv.conf (bind-mounted).
nameserver 8.8.8.8
nameserver 1.1.1.1
options timeout:2 attempts:2
`
)

// exitSTLSDNSServers is the dns block of the exit's sing-box (ExitSTLSServerJSON);
// ExitSTLSResolvConf names the same servers.
var exitSTLSDNSServers = []string{"8.8.8.8", "1.1.1.1"}

// ValidateExitIP is the caller contract of every exit renderer (ExitHysteriaServerYAML,
// ExitHysteriaACL, ExitSTLSServerJSON, ExitGuardConf, HubSTLSClientJSON): the exit
// address must be a unicast IP literal. ExitHysteriaServerYAML / ExitHysteriaACL cannot fail and
// silently leave out the own-address rules for anything else, so the provisioning core
// (internal/provision ExitRecipe, Task 2.8) and the CLI call this before rendering; the renderers
// that return an error call it themselves.
func ValidateExitIP(exitIP string) error {
	ip := net.ParseIP(strings.TrimSpace(exitIP))
	switch {
	case ip == nil:
		return fmt.Errorf("exit address %q is not an IP address", exitIP)
	case ip.IsUnspecified() || ip.IsLoopback() || ip.IsMulticast() || ip.IsLinkLocalUnicast() || ip.IsLinkLocalMulticast():
		return fmt.Errorf("exit address %s is not a unicast host address", ip)
	}
	return nil
}

// ExitGuardConf renders ExitGuardConfPath for the exit exitIP (ValidateExitIP) with the
// TCP ports allowed on its own address (the MTProxy ports; 0 = none), the same allowance as
// ExitHysteriaACL.
func ExitGuardConf(exitIP string, ownTCPPorts ...int) (string, error) {
	if err := ValidateExitIP(exitIP); err != nil {
		return "", err
	}
	ip := canonicalIP(exitIP)
	fam := "ip"
	if strings.Contains(ip, ":") {
		fam = "ip6"
	}
	var v4, v6 []string
	for _, n := range exitBlockedRanges {
		if strings.Contains(n, ":") {
			v6 = append(v6, n)
		} else {
			v4 = append(v4, n)
		}
	}
	v4 = append(v4, "224.0.0.0/4", "255.255.255.255/32")
	v6 = append(v6, "ff00::/8")
	set := func(s []string) string { return "{ " + strings.Join(s, ", ") + " }" }

	var b strings.Builder
	b.WriteString("# Generated by heyearth (config.ExitGuardConf): what the exit's backup tunnel (sing-box, user " + ExitSTLSUser + ") may not reach.\n")
	b.WriteString("table inet " + ExitGuardTable + "\ndelete table inet " + ExitGuardTable + "\ntable inet " + ExitGuardTable + " {\n")
	b.WriteString("  chain output {\n    type filter hook output priority filter; policy accept;\n")
	b.WriteString("    meta skuid \"" + ExitSTLSUser + "\" jump tunnel_egress\n  }\n")
	b.WriteString("  chain tunnel_egress {\n")
	for _, p := range validPorts(ownTCPPorts) {
		b.WriteString("    " + fam + " daddr " + ip + " tcp dport " + strconv.Itoa(p) + " return\n")
	}
	if fam == "ip" {
		v4 = append(v4, ip)
	} else {
		v6 = append(v6, ip)
	}
	b.WriteString("    ip daddr " + set(v4) + " counter reject\n")
	b.WriteString("    ip6 daddr " + set(v6) + " counter reject\n")
	b.WriteString("    fib daddr type { local, multicast, broadcast } counter reject\n")
	b.WriteString("  }\n}\n")
	return b.String(), nil
}

// ExitGuardUnit loads ExitGuardConfPath at boot, before the tunnel (which Requires= it), and
// again whenever nftables.service is restarted (PartOf=) or reloaded (ReloadPropagatedFrom= +
// ExecReload=: a reload's `flush ruleset` would drop the guard, and PartOf= does not propagate
// reloads). Ordered after nftables.service, so the reload lands after its flush.
const ExitGuardUnit = `[Unit]
Description=Kernel egress guard of the exit backup tunnel (HeYearth)
After=network.target nftables.service
PartOf=nftables.service
ReloadPropagatedFrom=nftables.service
Before=` + ExitSTLSUnit + `.service
[Service]
Type=oneshot
ExecStart=/usr/sbin/nft -f ` + ExitGuardConfPath + `
ExecReload=/usr/sbin/nft -f ` + ExitGuardConfPath + `
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
`

// ExitSTLSUserScript creates the system group and user sing-box runs as (no login, no home),
// once; a group left without its user is reused, not a useradd failure.
const ExitSTLSUserScript = `getent group ` + ExitSTLSUser + ` >/dev/null || groupadd --system ` + ExitSTLSUser + `
if ! id -u ` + ExitSTLSUser + ` >/dev/null 2>&1; then
  useradd --system -g ` + ExitSTLSUser + ` --no-create-home --shell /usr/sbin/nologin ` + ExitSTLSUser + `
  echo "[stls] system user ` + ExitSTLSUser + ` created"
fi
`

// ExitGuardApplyScript (re)loads the guard written to ExitGuardConfPath / ExitGuardUnitPath
// and enables its boot unit; under set -e a failure stops the caller.
const ExitGuardApplyScript = `nft -f ` + ExitGuardConfPath + `
systemctl daemon-reload
systemctl enable ` + ExitGuardService + ` >/dev/null 2>&1
echo "[stls] egress guard applied (table inet ` + ExitGuardTable + `, user ` + ExitSTLSUser + `)"
`
