package config

// The reserve entry's TCP 443 and 80 (block 3M / M7): a relay takes them in its own nginx stream
// instead of the nft DNAT, so the Hub sees every client's real address:
//
//	relay :443 -> Hub :RelayHubPPPort with a PROXY header (the client's address)
//	          -> Hub nginx stream relay-pp.conf: realip only from relays it trusts, then the same
//	             SNI routing as the 443 router into the PROXY mirrors 127.0.0.1:8446 (http nginx,
//	             realip) and 127.0.0.1:10444 (xray vless-reality-pp)
//	relay :80  -> Hub :80, plain (ACME http-01 when the site's domain points at a relay)
//
// So the site, the subscription link, YooKassa webhooks, per-IP limits and the audit work through
// a relay with real client IPs. The Hub trusts a PROXY header only from a relay's own address
// (set_real_ip_from, one file per relay in HubRelayTrustDir): anyone else connecting to the port
// is seen as themselves — a forged header changes nothing.

import (
	"bufio"
	"fmt"
	"regexp"
	"sort"
	"strings"
)

const (
	// RelayHubPPPort: the Hub's stream listener for relays (public; trust is per source address).
	RelayHubPPPort = 8447
	// RelayNginxConfPath: the relay's nginx.conf — the whole file is ours (stream only, no http).
	RelayNginxConfPath = "/etc/nginx/nginx.conf"
	// HubRelayPPConfPath: the Hub's stream server for relays (included by stream { … stream.d/*.conf }).
	HubRelayPPConfPath = "/etc/nginx/stream.d/relay-pp.conf"
	// HubRelayTrustDir: one set_real_ip_from file per relay, included by HubRelayPPConf.
	HubRelayTrustDir = "/etc/nginx/heyearth-relays"
	// HubStreamRouterPath: the Hub's 443 router whose SNI map relay-pp.conf mirrors.
	HubStreamRouterPath = "/etc/nginx/stream.d/heyearth.conf"
	// The PROXY mirrors of the Hub's backends (always present, whatever the 443 router's mode).
	hubNginxPPAddr = "127.0.0.1:8446"
	hubXrayPPAddr  = "127.0.0.1:10444"
)

// RelayStreamTCPPorts: the relay ports its nginx stream takes (443 with PROXY, 80 plain).
var RelayStreamTCPPorts = []int{80, 443}

// The relay → Hub connection is retried with a new connection (incident 2026-11-20): a transit
// link between the providers lost every packet of some 5-tuples towards one entry — the same
// source port always failed, another always passed, ping kept passing — so 40–60 % of the
// relay's connections to the Hub hung for the whole connect timeout and then died. Each try is
// a new socket, so a new source port and a new 5-tuple: with half of the tuples lost, 8 tries
// leave 0.4 %. nginx tries the next server of an upstream only, so the upstream lists the same
// Hub address RelayUpstreamTries times; max_fails=0 keeps a server that just failed in the group
// (otherwise all copies would be marked down together and nginx would answer «no live upstreams»).
const (
	RelayUpstreamTries   = 8
	RelayConnectTimeout  = "1s"  // RTT to the Hub is ~45 ms; a lost SYN costs one try, not 10 s
	RelayNextUpstreamCap = "10s" // all tries of one client connection together
)

// relayUpstream is an upstream block of RelayUpstreamTries copies of addr.
func relayUpstream(name, addr string) string {
	var b strings.Builder
	b.WriteString("    upstream " + name + " {\n")
	for range RelayUpstreamTries {
		b.WriteString("        server " + addr + " max_fails=0;\n")
	}
	b.WriteString("    }\n")
	return b.String()
}

// RelayNginxConf is the relay's nginx.conf for the Hub address hubIP: stream only (no http block,
// so the package's default site never listens), 443 to the Hub's relay listener with a PROXY
// header, 80 to the Hub's port 80, each connection to the Hub retried on a new 5-tuple.
func RelayNginxConf(hubIP string) (string, error) {
	hub, err := RelayHubIP(hubIP)
	if err != nil {
		return "", err
	}
	h := hub.String()
	retry := fmt.Sprintf(`        proxy_connect_timeout %s;
        proxy_next_upstream on;
        proxy_next_upstream_tries %d;
        proxy_next_upstream_timeout %s;
`, RelayConnectTimeout, RelayUpstreamTries, RelayNextUpstreamCap)
	return fmt.Sprintf(`# Generated by heyearth (config.RelayNginxConf): reserve entry, TCP 443/80 to the Hub %[1]s. Do not edit.
user www-data;
worker_processes auto;
worker_rlimit_nofile 65535;
pid /run/nginx.pid;
error_log /var/log/nginx/error.log warn;
include /etc/nginx/modules-enabled/*.conf;

events {
    worker_connections 16384;
}

stream {
    # The same Hub address %[4]d times: a failed connect is retried on a new connection, so on a
    # new source port (a transit link may lose some 5-tuples entirely).
%[2]s%[3]s
    # Users: Reality «Берёза», the site and the subscription. The PROXY header tells the Hub the
    # client's real address.
    server {
        listen 443 so_keepalive=60s:10s:3;
        proxy_pass heyearth_hub_pp;
        proxy_protocol on;
%[5]s        proxy_timeout 3600s;
    }
    # The site's certificate renewal (ACME http-01) when its domain points at this entry.
    server {
        listen 80;
        proxy_pass heyearth_hub_80;
%[5]s        proxy_timeout 60s;
    }
}
`, h,
		relayUpstream("heyearth_hub_pp", fmt.Sprintf("%s:%d", h, RelayHubPPPort)),
		relayUpstream("heyearth_hub_80", h+":80"),
		RelayUpstreamTries, retry), nil
}

// HubRelayTrustFile is the Hub's trust file of one relay: its address may set the client address.
func HubRelayTrustFile(relayIP string) (string, error) {
	ip, err := RelayHubIP(relayIP) // the same public-IPv4 rules as a Hub address
	if err != nil {
		return "", fmt.Errorf("адрес ретранслятора: %w", err)
	}
	return "# Generated by heyearth: reserve entry " + ip.String() + " may tell the Hub its client's address.\nset_real_ip_from " + ip.String() + ";\n", nil
}

// HubRelayTrustPath: the trust file of a relay (by its address).
func HubRelayTrustPath(relayIP string) string {
	return HubRelayTrustDir + "/" + strings.ReplaceAll(strings.TrimSpace(relayIP), ":", "_") + ".conf"
}

var (
	reRouterMapHead = regexp.MustCompile(`^map\s+\$ssl_preread_server_name\s+\$backend\s*\{`)
	reMapEntry      = regexp.MustCompile(`^([A-Za-z0-9.*_-]+)\s+([A-Za-z0-9_]+)\s*;`)
	reUpstreamHead  = regexp.MustCompile(`^upstream\s+([A-Za-z0-9_]+)\s*\{`)
	reUpstreamAddr  = regexp.MustCompile(`^server\s+127\.0\.0\.1:(\d+)`)
)

// RouterSiteNames reads, from the Hub's 443 router (HubStreamRouterPath), the server names its SNI
// map sends to the http nginx (an upstream on 8443 or 8446): those go to the http mirror, the
// rest — Reality — to xray. An error when the map or any http name is missing: a relay-pp.conf
// that routed the site to xray would break the site silently.
func RouterSiteNames(router string) ([]string, error) {
	nginxUpstreams := map[string]bool{}
	type entry struct{ name, up string }
	var entries []entry
	inMap, inUpstream := false, ""
	sc := bufio.NewScanner(strings.NewReader(router))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if i := strings.Index(line, "#"); i >= 0 {
			line = strings.TrimSpace(line[:i])
		}
		switch {
		case reRouterMapHead.MatchString(line):
			inMap = true
		case inMap && strings.HasPrefix(line, "}"):
			inMap = false
		case inMap:
			if m := reMapEntry.FindStringSubmatch(line); m != nil && m[1] != "default" && m[1] != "hostnames" {
				entries = append(entries, entry{m[1], m[2]})
			}
		case reUpstreamHead.MatchString(line):
			inUpstream = reUpstreamHead.FindStringSubmatch(line)[1]
		case inUpstream != "" && strings.HasPrefix(line, "}"):
			inUpstream = ""
		case inUpstream != "":
			if m := reUpstreamAddr.FindStringSubmatch(line); m != nil && (m[1] == "8443" || m[1] == "8446") {
				nginxUpstreams[inUpstream] = true
			}
		}
	}
	var names []string
	for _, e := range entries {
		if nginxUpstreams[e.up] {
			names = append(names, e.name)
		}
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("в %s не найдено имён сайта (map $backend → upstream на 8443/8446)", HubStreamRouterPath)
	}
	sort.Strings(names)
	return names, nil
}

// HubRelayPPConf is the Hub's stream server for relays: PROXY in (realip only from the trust
// files), the site's names to the http mirror, everything else (Reality) to the xray mirror, PROXY
// out with the client's real address.
func HubRelayPPConf(siteNames []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by heyearth (config.HubRelayPPConf): TCP 443 of the reserve entries arrives here. Do not edit.\n")
	b.WriteString("map $ssl_preread_server_name $relay_backend {\n")
	for _, n := range siteNames {
		fmt.Fprintf(&b, "    %-28s relay_nginx_pp;\n", n)
	}
	b.WriteString("    default                      relay_xray_pp;\n}\n\n")
	fmt.Fprintf(&b, "upstream relay_nginx_pp {\n    server %s;\n}\n\nupstream relay_xray_pp {\n    server %s;\n}\n\n", hubNginxPPAddr, hubXrayPPAddr)
	fmt.Fprintf(&b, `server {
    listen %d proxy_protocol so_keepalive=60s:10s:3;
    # Only a reserve entry may set the client's address (one file per entry).
    include %s/*.conf;
    ssl_preread on;
    proxy_protocol on;
    proxy_timeout 3600s;
    proxy_pass $relay_backend;
}
`, RelayHubPPPort, HubRelayTrustDir)
	return b.String()
}

