package config

import "fmt"

// HubHysteriaDir holds the Hub's per-exit hysteria client configs (client-<id>.yaml).
const HubHysteriaDir = "/opt/heyearth/hysteria"

// ExitHopRange is the UDP range every exit redirects to its hysteria server (:50443) and the
// Hub's clients hop across (ExitPortHopScript, HubHysteriaClientYAML).
const ExitHopRange = "20000-50000"

// HubHysteriaClientYAML renders /opt/heyearth/hysteria/client-<id>.yaml, the Hub's hysteria
// client to exit <id>: port hopping across the exit's ExitHopRange (hopInterval 30 s), the
// tunnel password, a local SOCKS5 on 127.0.0.1:<socksPort> (1088 + id) and the client-side
// P1-hardening ACL. Tuning = what production runs and what the 2026-10-12 Hub→exit benchmark on
// hysteria 2.13 found best: Brutal with bandwidth up/down 100 mbps (BBR was 3–4× slower), QUIC
// stream windows 26843545 and connection windows 67108864 (as the exit servers) — so a
// re-provisioning never silently changes production tuning. The single template of every path
// that writes it: heyearth-api (internal/biz hub_provisioner, server lifecycle) and
// deploy --setup-exit-node.
func HubHysteriaClientYAML(serverID int, exitIP, authKey string, socksPort int) string {
	return fmt.Sprintf(`# Generated by heyearth (config.HubHysteriaClientYAML) for server id=%d
server: %s:`+ExitHopRange+`

auth: %s

tls:
  insecure: true

transport:
  udp:
    hopInterval: 30s

quic:
  initStreamReceiveWindow: 26843545
  maxStreamReceiveWindow: 26843545
  initConnReceiveWindow: 67108864
  maxConnReceiveWindow: 67108864

bandwidth:
  up: 100 mbps
  down: 100 mbps

socks5:
  listen: 127.0.0.1:%d

# ─── ACL: P1-hardening block-list ───
# Reject private CIDRs + port 0 + BitTorrent ports at the client side.
acl:
  inline:
    - reject(10.0.0.0/8)
    - reject(172.16.0.0/12)
    - reject(192.168.0.0/16)
    - reject(127.0.0.0/8)
    - reject(all, tcp/0)
    - reject(all, udp/0)
    - reject(all, tcp/6881-6889)
    - reject(all, udp/6881-6889)
    - reject(all, tcp/51413)
    - reject(all, udp/51413)
    - direct(all)
`, serverID, exitIP, authKey, socksPort)
}

// HubHysteriaClientUnit renders /etc/systemd/system/hysteria2-client-<id>.service (runs as root).
func HubHysteriaClientUnit(serverID int, exitIP string) string {
	return fmt.Sprintf(`[Unit]
Description=Hysteria2 Client for server id=%d (%s) — HeYearth
After=network.target

[Service]
Type=simple
ExecStart=/usr/local/bin/hysteria client -c %s/client-%d.yaml
Restart=always
RestartSec=3
LimitNOFILE=65535

[Install]
WantedBy=multi-user.target
`, serverID, exitIP, HubHysteriaDir, serverID)
}

// ExitPortHopScript makes an exit accept the Hub clients' port hopping: UDP ExitHopRange is
// redirected to the hysteria server on :50443 (nft table inet hysteria_porthopping, re-applied
// at boot by nftables-hysteria.service). Idempotent: the file creates the table if missing,
// deletes it and defines it again in one nft transaction, so a re-run never duplicates the rule.
// Same table, file and unit as the admin panel's exit setup step 4. Built from the file
// templates the provisioning core writes (ExitPortHopConf, ExitPortHopUnit; exit_node.go).
const ExitPortHopScript = `command -v nft >/dev/null 2>&1 || apt-get install -y -qq nftables >/dev/null 2>&1 || true
cat > ` + ExitPortHopConfPath + ` << 'NEOF'
` + ExitPortHopConf + `NEOF
nft -f ` + ExitPortHopConfPath + `
cat > ` + ExitPortHopUnitPath + ` << 'SEOF'
` + ExitPortHopUnit + `SEOF
systemctl daemon-reload
systemctl enable nftables-hysteria >/dev/null 2>&1 || true
`
