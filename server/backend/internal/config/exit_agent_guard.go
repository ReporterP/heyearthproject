package config

import (
	"errors"
	"net"
	"sort"
	"strconv"
	"strings"
)

// node-agent's Hub-only guard (Beads cudk.77). node-agent serves mTLS gRPC on TCP 50052
// (NodeAgentPort); its CA key was once public, so the port must never be open to the world,
// whatever the exit's firewall (ufw is often off on a fresh VPS, ExitFirewallScript never turns
// it on). An nftables input chain of its own table, ExitAgentGuardTable, drops TCP 50052 from
// everyone but the Hub's addresses and loopback — what the hand-made guard on exit 2 does
// (2026-10-15: 138.16.181.225, 45.150.39.236, 109.172.86.40, 127.0.0.1, ::1). Like the xray
// guard (exit_xray_guard.go) the file creates, deletes and defines the table in one nft
// transaction, the oneshot ExitAgentGuardUnit loads it at boot and again after
// `systemctl restart nftables` (PartOf=), and node-agent Requires= it (NodeAgentUnit): the agent
// never listens unguarded. Deprovision keeps the guard (a parked node keeps 50052 closed).

// ExitAgentGuardUnitPath is the guard's boot unit.
const ExitAgentGuardUnitPath = "/etc/systemd/system/" + ExitAgentGuardService + ".service"

// ExitAgentGuardConf renders ExitAgentGuardConfPath: TCP 50052 accepted from hubIPs (the Hub's
// addresses, the same list the firewall step allows 50052 from — ExitOptions.HubIPs), 127.0.0.1
// and ::1, dropped from everyone else. Addresses are canonicalised, de-duplicated and sorted (the
// file is byte-stable whatever the order of the list); entries that are not unicast host IPs
// are left out, and a list without a single usable address is an error: the guard would lock
// the Hub out of every node-agent.
func ExitAgentGuardConf(hubIPs []string) (string, error) {
	var v4, v6 []string
	seen := map[string]bool{}
	for _, h := range hubIPs {
		ip := net.ParseIP(strings.TrimSpace(h))
		if ip == nil || ip.IsUnspecified() || ip.IsLoopback() || ip.IsMulticast() || ip.IsLinkLocalUnicast() {
			continue
		}
		s := ip.String()
		if seen[s] {
			continue
		}
		seen[s] = true
		if ip.To4() != nil {
			v4 = append(v4, s)
		} else {
			v6 = append(v6, s)
		}
	}
	if len(v4)+len(v6) == 0 {
		return "", errors.New("no usable Hub address for the node-agent guard: it would lock the Hub out of node-agent")
	}
	sort.Strings(v4)
	sort.Strings(v6)
	port := strconv.Itoa(NodeAgentPort)
	var b strings.Builder
	b.WriteString("# Generated by heyearth (config.ExitAgentGuardConf): node-agent (TCP " + port + ") only from the Hub and loopback.\n")
	b.WriteString("table inet " + ExitAgentGuardTable + "\ndelete table inet " + ExitAgentGuardTable + "\ntable inet " + ExitAgentGuardTable + " {\n")
	b.WriteString("  chain input {\n    type filter hook input priority filter; policy accept;\n")
	b.WriteString("    tcp dport " + port + " ip saddr { " + strings.Join(append(v4, "127.0.0.1"), ", ") + " } accept\n")
	b.WriteString("    tcp dport " + port + " ip6 saddr { " + strings.Join(append(v6, "::1"), ", ") + " } accept\n")
	b.WriteString("    tcp dport " + port + " counter drop\n")
	b.WriteString("  }\n}\n")
	return b.String(), nil
}

// ExitAgentGuardUnit loads ExitAgentGuardConfPath at boot, before node-agent (which Requires= it),
// and again whenever nftables.service is restarted (PartOf=; its ruleset flush would drop it).
const ExitAgentGuardUnit = `[Unit]
Description=node-agent (TCP ` + "50052" + `) only from the Hub (HeYearth)
After=network-pre.target nftables.service
PartOf=nftables.service
Before=node-agent.service
[Service]
Type=oneshot
ExecStart=/usr/sbin/nft -f ` + ExitAgentGuardConfPath + `
RemainAfterExit=yes
[Install]
WantedBy=multi-user.target
`

// ExitAgentGuardApplyScript (re)loads the guard written to ExitAgentGuardConfPath /
// ExitAgentGuardUnitPath, enables its boot unit and starts it (a no-op when it already runs —
// the table is reloaded by `nft -f` either way; a started unit is what PartOf= re-runs after an
// nftables restart). Run as root under set -e: a failure stops the caller before node-agent
// (re)starts — the converge extra of node-agent.
const ExitAgentGuardApplyScript = `nft -f ` + ExitAgentGuardConfPath + `
systemctl daemon-reload
systemctl enable ` + ExitAgentGuardService + ` >/dev/null 2>&1
systemctl start ` + ExitAgentGuardService + `
echo "[node-agent] TCP 50052 — только с адресов Hub (table inet ` + ExitAgentGuardTable + `)"
`

// NodeAgentCheckScript prints LISTEN=0|1 (node-agent on TCP 50052) and GUARD=0|1 (the Hub-only
// guard's drop rule for TCP 50052 is loaded).
const NodeAgentCheckScript = `# hp:agent-check
if ss -Htlpn 'sport = :50052' 2>/dev/null | grep -q '"node-agent"'; then echo LISTEN=1; else echo LISTEN=0; fi
if nft list table inet ` + ExitAgentGuardTable + ` 2>/dev/null | grep -q 'tcp dport 50052 counter .*drop'; then echo GUARD=1; else echo GUARD=0; fi
`
