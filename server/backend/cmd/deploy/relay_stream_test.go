const relayStreamTestHub = "203.0.113.10"

// relayStreamHarness runs the entry script against a temp nginx.conf with stubbed nginx,
// systemctl and python3 (the stub prints the CHECK lines of checks, one per call).
func relayStreamHarness(t *testing.T, current string, nginxOK bool, checks []string, apply bool) (out string, exit int, conf, prev string) {
	t.Helper()
	dir := t.TempDir()
	bin := filepath.Join(dir, "bin")
	if err := os.MkdirAll(bin, 0o755); err != nil {
		t.Fatal(err)
	}
	conf = filepath.Join(dir, "nginx.conf")
	write := func(p, s string, mode os.FileMode) {
		if err := os.WriteFile(p, []byte(s), mode); err != nil {
			t.Fatal(err)
		}
	}
	write(conf, current, 0o644)
	write(filepath.Join(dir, "checks"), strings.Join(checks, "\n")+"\n", 0o644)
	nginxRC := "0"
	if !nginxOK {
		nginxRC = "1"
	}
	write(filepath.Join(bin, "nginx"), "#!/bin/bash\necho nginx-t-stub >&2\nexit "+nginxRC+"\n", 0o755)
	write(filepath.Join(bin, "systemctl"), "#!/bin/bash\necho \"systemctl $*\" >> "+shQuote(shellDir(filepath.Join(dir, "calls")))+"\n", 0o755)
	write(filepath.Join(bin, "python3"), "#!/bin/bash\nn=$(cat "+shQuote(shellDir(filepath.Join(dir, "n")))+" 2>/dev/null || echo 0); n=$((n+1)); echo $n > "+
		shQuote(shellDir(filepath.Join(dir, "n")))+"\nsed -n \"${n}p\" "+shQuote(shellDir(filepath.Join(dir, "checks")))+"\n", 0o755)
	newConf, err := config.RelayNginxConf(relayStreamTestHub)
	if err != nil {
		t.Fatal(err)
	}
	script := "export PATH=" + shQuote(shellDir(bin)) + ":$PATH RELAY_NGINX_CONF=" + shQuote(shellDir(conf)) + "\n" +
		relayStreamEntryScript(newConf, relayStreamTestHub, "yandex.ru", relayStreamTestHub, apply)
	out, exit = runBash(t, script)
	c, _ := os.ReadFile(conf)
	p, _ := os.ReadFile(conf + ".heyearth-prev")
	return out, exit, string(c), string(p)
}

// oldRelayConf is a relay nginx.conf as the recipe wrote it before the retries (its first line is
// the marker the script checks).
const oldRelayConf = "# Generated by heyearth (config.RelayNginxConf): reserve entry, TCP 443/80 to the Hub " + relayStreamTestHub + ". Do not edit.\nstream { server { listen 443; proxy_pass " + relayStreamTestHub + ":8447; proxy_connect_timeout 10s; } }\n"

func TestRelayStreamEntryScript(t *testing.T) {
	if !haveBash() {
		t.Skip("no bash")
	}
	newConf, _ := config.RelayNginxConf(relayStreamTestHub)

	t.Run("better after the change: kept, previous saved", func(t *testing.T) {
		out, exit, conf, prev := relayStreamHarness(t, oldRelayConf, true,
			[]string{"CHECK tls=21/40 http=6/10", "CHECK tls=40/40 http=10/10"}, true)
		if exit != 0 || !strings.Contains(out, "RELAY_STREAM_OK TLS до 52% → после 100%") {
			t.Fatalf("exit %d:\n%s", exit, out)
		}
		if conf != newConf || prev != oldRelayConf {
			t.Errorf("conf not replaced or previous not kept:\nconf=%q\nprev=%q", conf, prev)
		}
	})

	t.Run("worse after the change: rolled back", func(t *testing.T) {
		out, exit, conf, _ := relayStreamHarness(t, oldRelayConf, true,
			[]string{"CHECK tls=30/40 http=10/10", "CHECK tls=20/40 http=10/10"}, true)
		if exit == 0 || !strings.Contains(out, "RELAY_STREAM_FAIL") || !strings.Contains(out, "откат") {
			t.Fatalf("exit %d:\n%s", exit, out)
		}
		if conf != oldRelayConf {
			t.Errorf("the previous config did not come back: %q", conf)
		}
	})

	t.Run("a healthy entry with one probe of noise: kept", func(t *testing.T) {
		out, exit, conf, _ := relayStreamHarness(t, oldRelayConf, true,
			[]string{"CHECK tls=40/40 http=10/10", "CHECK tls=39/40 http=10/10"}, true)
		if exit != 0 || conf != newConf {
			t.Fatalf("97%% after 100%% is noise, not a regression (exit %d):\n%s", exit, out)
		}
	})

	t.Run("below the floor even if better: rolled back", func(t *testing.T) {
		out, exit, conf, _ := relayStreamHarness(t, oldRelayConf, true,
			[]string{"CHECK tls=10/40 http=10/10", "CHECK tls=30/40 http=10/10"}, true)
		if exit == 0 || conf != oldRelayConf {
			t.Fatalf("75%% after the change must roll back (exit %d):\n%s", exit, out)
		}
	})

	t.Run("nginx -t fails: previous restored, no reload", func(t *testing.T) {
		out, exit, conf, _ := relayStreamHarness(t, oldRelayConf, false,
			[]string{"CHECK tls=21/40 http=6/10"}, true)
		if exit == 0 || !strings.Contains(out, "nginx -t не прошёл") || conf != oldRelayConf {
			t.Fatalf("exit %d conf changed=%v:\n%s", exit, conf != oldRelayConf, out)
		}
	})

	t.Run("a foreign nginx.conf is never touched", func(t *testing.T) {
		foreign := "user www-data;\nevents {}\n"
		out, exit, conf, _ := relayStreamHarness(t, foreign, true, nil, true)
		if exit == 0 || conf != foreign || !strings.Contains(out, "не рецептом входа") {
			t.Fatalf("exit %d:\n%s", exit, out)
		}
	})

	t.Run("a config pointing at another Hub is never touched", func(t *testing.T) {
		other := strings.ReplaceAll(oldRelayConf, relayStreamTestHub, "198.51.100.7")
		out, exit, conf, _ := relayStreamHarness(t, other, true, nil, true)
		if exit == 0 || conf != other || !strings.Contains(out, "ведёт не на Hub") {
			t.Fatalf("exit %d:\n%s", exit, out)
		}
	})

	t.Run("check only: measures, changes nothing", func(t *testing.T) {
		out, exit, conf, prev := relayStreamHarness(t, oldRelayConf, true,
			[]string{"CHECK tls=21/40 http=6/10"}, false)
		if exit != 0 || !strings.Contains(out, "before: CHECK tls=21/40") || conf != oldRelayConf || prev != "" {
			t.Fatalf("exit %d:\n%s", exit, out)
		}
	})
}

// The Hub-side launcher parses as bash, takes the lock before anything else, detaches the run
// (setsid, stdin closed) and carries the run script intact.
func TestRelayStreamLaunchScript(t *testing.T) {
	run := "echo RELAY_STREAM_OK 'quoted $x'\n"
	s := hubJobLaunchScript("relay-stream", 6, run)
	for _, must := range []string{"flock -n 9", "setsid bash -c", "</dev/null", "/var/log/heyearth-relay-stream-6.log", "echo HEYEARTH_JOB_STARTED", "HEYEARTH_JOB_DONE"} {
		if !strings.Contains(s, must) {
			t.Errorf("launcher lacks %q:\n%s", must, s)
		}
	}
	if strings.Index(s, "flock -n 9") > strings.Index(s, "setsid") {
		t.Error("the lock must be taken before the run starts")
	}
	if !haveBash() {
		t.Skip("no bash")
	}
	if out, rc := runBashStdin(t, s, "-n"); rc != 0 {
		t.Fatalf("launcher does not parse: %s", out)
	}
	// The embedded run script decodes back byte for byte.
	out, rc := runBash(t, `printf '%s' `+lineAfter(s, "printf '%s' ")+` >/dev/null; echo ok`)
	if rc != 0 || !strings.Contains(out, "ok") {
		t.Fatalf("payload line broken: %s", out)
	}
}

// lineAfter returns the shell word that follows prefix on its line in s.
func lineAfter(s, prefix string) string {
	i := strings.Index(s, prefix)
	if i < 0 {
		return "''"
	}
	rest := s[i+len(prefix):]
	if j := strings.Index(rest, " | base64"); j >= 0 {
		return rest[:j]
	}
	return "''"
}

